#!/usr/bin/env python3
"""Emit a launch bundle (shell + notes) from a feasible plan.

Does not submit to LSF — safe to run anywhere. On TSRI/farm hosts, review
then execute the generated run.sh under your module environment.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from textwrap import dedent

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from plan_calibre_job import plan_job  # noqa: E402


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--farm", type=Path, default=ROOT / "configs" / "farm.yaml")
    p.add_argument("--job", type=Path, required=True)
    p.add_argument(
        "--out-dir",
        type=Path,
        default=ROOT / "results" / "launch_bundle",
    )
    args = p.parse_args()

    farm = yaml.safe_load(args.farm.read_text())
    job_doc = yaml.safe_load(args.job.read_text())
    job = job_doc["job"]
    plan = plan_job(farm, job)
    args.out_dir.mkdir(parents=True, exist_ok=True)

    (args.out_dir / "plan.json").write_text(json.dumps(plan.to_dict(), indent=2) + "\n")

    if plan.status == "BLOCKED":
        (args.out_dir / "BLOCKED.txt").write_text(
            "\n".join(plan.blockers) + "\n"
        )
        print(f"status=BLOCKED out={args.out_dir}")
        return 2

    run_sh = dedent(
        f"""\
        #!/usr/bin/env bash
        # AUTO-GENERATED by emit_launch_bundle.py — review before submit.
        # Farm semantics: 1 LSF slot = 1 CPU core (TSRI EDA Cloud guide).
        set -euo pipefail

        echo "PLAN status={plan.status}"
        echo "remote_slaves={plan.remote_slaves} turbo={plan.turbo}"
        echo "licenses_needed={plan.licenses_needed}"

        module load calibre

        # Master often needs a single slot; children are remote LSF jobs.
        # Configure Concurrent Jobs={plan.remote_slaves} and turbo={plan.turbo}
        # in Calibre mmDRC / PERC GUI or remote config to match this plan.
        #
        # Example single-host turbo-only (no remote) smoke:
        #   bsub -q {plan.queue} -n {plan.turbo} \\\\
        #     calibre -{plan.flow} -hier -turbo {plan.turbo} {job.get('ruledeck','RULE.rule')}
        #
        # Recommended remote master stub (1 slot):
        bsub -q {plan.queue} -n {plan.master_slots} \\\\
          -R "select[mem>{plan.mem_gb_per_slave}]" \\\\
          -o {job.get('name','calibre_job')}.%J.log \\\\
          -e {job.get('name','calibre_job')}.%J.err \\\\
          "echo REVIEW_REMOTE_CONFIG slaves={plan.remote_slaves} turbo={plan.turbo}; {plan.calibre_args}"

        echo "After submit: busers ; bjobs -u $USER ; lmstat -a | head"
        """
    )
    run_path = args.out_dir / "run.sh"
    run_path.write_text(run_sh)
    run_path.chmod(0o755)

    notes = dedent(
        f"""\
        # Launch notes — {job.get('name')}

        status: {plan.status}
        queue: {plan.queue}
        remote_slaves × turbo: {plan.remote_slaves} × {plan.turbo} = {plan.total_compute_slots} child slots
        master_slots: {plan.master_slots}
        charged_slots (planning): {plan.total_slots_charged}
        licenses_needed: {plan.licenses_needed}

        Checklist before real submit
        - [ ] `busers` shows free slots ≥ charged_slots + headroom
        - [ ] `lmstat` shows free tokens ≥ licenses_needed
        - [ ] Calibre remote Concurrent Jobs == {plan.remote_slaves}
        - [ ] Calibre -turbo / CPU-per-host == {plan.turbo}
        - [ ] Limit Jobs enabled (TSRI Custom Compiler guidance)
        - [ ] hyperflex/hyper == {plan.enable_hyperflex} (prefer false until measured)
        - [ ] After done: `bacct -l <jobId>` — HOG_FACTOR ≈ cores, CPU_EFFICIENCY ≈ 100%

        Warnings
        {chr(10).join('- ' + w for w in plan.warnings) or '- (none)'}
        """
    )
    (args.out_dir / "NOTES.md").write_text(notes)
    print(f"status={plan.status}")
    print(f"out={args.out_dir}")
    print(f"run={run_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
